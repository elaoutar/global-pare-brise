export const LISTE_MARQUES_MAROC = Object.keys(MARQUES_ET_MODELES_MAROC);

export function getModelesPourMarque(marque: string): string[] {
  if (!marque) return [];
  // Case-insensitive matching or exact lookup
  const exact = MARQUES_ET_MODELES_MAROC[marque];
  if (exact) return exact;

  const foundKey = Object.keys(MARQUES_ET_MODELES_MAROC).find(
    (k) => k.toLowerCase() === marque.trim().toLowerCase()
  );
  return foundKey ? MARQUES_ET_MODELES_MAROC[foundKey] : [];
}
